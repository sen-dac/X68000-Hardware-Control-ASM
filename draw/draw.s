;------------------------------------------------------------------------------
; 16色 BMP からパレットをロード
;------------------------------------------------------------------------------
; 対象：
; $E82000 ～ GR       パレット(16色モードの場合のみ)(PB:0～PB:15)
; $E82200 ～ SP/BG/TX パレット(PB:0)(常時16色)
; $E82220 ～ SP/BG    パレット(PB:1～PB:15)(常時16色)
;------------------------------------------------------------------------------
; - IN:   a0.l    filename : ロードするBMPファイル名
;         a1.l    pal      : パレットを格納するアドレス
;
; - OUT:  d0.l    ret      : 0:失敗 / 1:成功
;------------------------------------------------------------------------------
; - MEMO:
;   BGでパレット0番を透明にできる条件(XM6,Zで動作確認済み)
;
; 1.透明色(0番)のRGB全てをオール0(黒)にすること
;   XM6,Z共に黒以外だと透過しない.
;   なお、0番でなくてもオール0(黒)だと透明扱いになってしまう.
;   透明ではない黒を使いたい場合、RGBを各8以上
;   (15bitカラー化で/8しても0にならない値)
;   の限りなく黒に近い色を使用する.
;
; 2.輝度(末尾1bit)を1ではなく0にすること.
;   他の色の輝度を0にしても今のところ影響が無い.
;
; ※ 当初PB0のみ可能と思われたが、後にどのPBでも可能だと判明
;------------------------------------------------------------------------------
D0123A1_LoadBmpPal16RGB .macro

        ; r, g, b, - 読み込む
        move.l  #4,-(sp)                ; 読み込むバイト数
        pea.l   color                   ; 書き込むバッファ
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _READ                   ; $FF3F read 読み込む
        lea     10(sp),sp               ; sp戻し

        ; 15bitカラー化(8bit→5bit)
        move.b  color_b,d0              ; B(青)
        lsr.w   #2,d0                   ; 右に2ビットシフト
        and.w   #%0000000000111110,d0   ;

        move.b  color_r,d1              ; R(赤)
        lsl.w   #3,d1                   ; 左に3ビットシフト
        and.w   #%0000011111000000,d1   ;

        move.b  color_g,d2              ; G(緑)
        lsl.w   #8,d2                   ; 左に8ビットシフト
        and.w   #%1111100000000000,d2   ;

        or.w    d1,d0                   ; 赤 or 青
        or.w    d2,d0                   ; 緑 or 赤青
        move.w  d0,(a1)
        addq.l  #2,a1                   ; 次のワードデータへ

                .endm

D0123A01_LoadBmpPal16::

        ; ファイルオープン
        clr.w   -(sp)                   ; #0:読み込みオープン
        move.l  a0,-(sp)                ; ファイル名
        DOS     _OPEN                   ; $FF3D open 主として読み込み専用に使われる
        addq.l  #6,sp                   ; sp戻し
        tst.l   d0                      ; もしd0.lが負の値なら
        bmi     @f                      ; ファイルオープン失敗なので飛ぶ
        move.l  d0,d3                   ; ファイルハンドルを保存

        ; パレット位置にシーク
        clr.w   -(sp)                   ; #0:シークモード0:ファイルの先頭から
        move.l  #54,-(sp)               ; オフセット 54バイト進める
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _SEEK                   ; $FF42 seek
        addq.l  #8,sp                   ; sp戻し

        ; パレットを読み込む(固定回数のためループ展開)
        D0123A1_LoadBmpPal16RGB         ; 色番号：00
        D0123A1_LoadBmpPal16RGB         ; 色番号：01
        D0123A1_LoadBmpPal16RGB         ; 色番号：02
        D0123A1_LoadBmpPal16RGB         ; 色番号：03
        D0123A1_LoadBmpPal16RGB         ; 色番号：04
        D0123A1_LoadBmpPal16RGB         ; 色番号：05
        D0123A1_LoadBmpPal16RGB         ; 色番号：06
        D0123A1_LoadBmpPal16RGB         ; 色番号：07
        D0123A1_LoadBmpPal16RGB         ; 色番号：08
        D0123A1_LoadBmpPal16RGB         ; 色番号：09
        D0123A1_LoadBmpPal16RGB         ; 色番号：10
