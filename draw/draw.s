;------------------------------------------------------------------------------
; 16色 BMP から画像をロード
; グラフィック画面(16色) / テキスト画面 共通
;------------------------------------------------------------------------------
; - IN:   a0.l    filename : ロードするBMPファイル名
;         a1.l    img      : 画像を格納するアドレス
;------------------------------------------------------------------------------
; - MEMO:
;   画像の上下反転処理は行わない. 事前に読み込む画像側を上下反転させておくこと.
;------------------------------------------------------------------------------
D0123A01_LoadBmpImage16::

        ; ファイルオープン
        clr.w   -(sp)                   ; #0:読み込みオープン
        move.l  a0,-(sp)                ; ファイル名
        DOS     _OPEN                   ; $FF3D open 主として読み込み専用に使われる
        addq.l  #6,sp                   ; sp戻し
        tst.l   d0                      ; もしd0.lが負の値なら
        bmi     @f                      ; ファイルオープン失敗なので飛ぶ
        move.l  d0,d3                   ; ファイルハンドルを保存

        ; 画像の横幅位置にシーク
        clr.w   -(sp)                   ; #0:シークモード0:ファイルの先頭から
        move.l  #18,-(sp)               ; オフセット 先頭から18バイト
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _SEEK                   ; $FF42 seek
        addq.l  #8,sp                   ; sp戻し

        ; 画像の横幅を読み込む
        move.l  #4,-(sp)                ; 読み込むバイト数
        pea.l   width                   ; 書き込むバッファ
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _READ                   ; $FF3F read 読み込む
        lea     10(sp),sp               ; sp戻し
        move.w  width,d1
        ror.w   #8,d1                   ; Intel対策(2バイトのデータが左右逆なのでローテートで元に戻す)

        ; 画像の縦幅位置にシーク
        clr.w   -(sp)                   ; #0:シークモード0:ファイルの先頭から
        move.l  #22,-(sp)               ; オフセット 先頭から22バイト
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _SEEK                   ; $FF42 seek
        addq.l  #8,sp                   ; sp戻し

        ; 画像の縦幅を読み込む
        move.l  #4,-(sp)                ; 読み込むバイト数
        pea.l   height                  ; 書き込むバッファ
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _READ                   ; $FF3F read 読み込む
        lea     10(sp),sp               ; sp戻し
        move.w  height,d2
        ror.w   #8,d2                   ; Intel対策(2バイトのデータが左右逆なのでローテートで元に戻す)

        ; 横幅と縦幅から画像を読み込むバイト数を求める
        mulu.w  d2,d1                   ; d1*=d2

        ; 画像の位置にシーク
        clr.w   -(sp)                   ; #0:シークモード0:ファイルの先頭から
        move.l  #118,-(sp)              ; オフセット 先頭から118バイト
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _SEEK                   ; $FF42 seek
        addq.l  #8,sp                   ; sp戻し

        ; 画像を読み込む
        move.l  d1,-(sp)               ; 読み込むバイト数

        pea.l   (a1)                    ; 書き込むバッファ
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _READ                   ; $FF3F read 読み込む
        lea     10(sp),sp               ; sp戻し

        ; ファイルクローズ
        move.w  d3,-(sp)                ; ファイルハンドル
        DOS     _CLOSE                  ; $FF3E close
        addq.l  #2,sp                   ; sp戻し
@@:
        rts

;------------------------------------------------------------------------------
;  BMP配列 → GR配列 変換
;------------------------------------------------------------------------------
; - IN:   a0.l    src       : 変換前データ(BMP)の先頭アドレス(W*H/2バイト)
;         a1.l    dst       : 変換後データ(GR)の先頭アドレス (W*H*2バイト)
;         d0.w    cnt       : ループ回数：W*H/2
;------------------------------------------------------------------------------
D01A01_BmpToGR::

        subq.w  #1,d0                   ; ループ回数設定 #n-1 は n回ループである事を強調した書き方
@@:
        move.b  (a0),d1                 ; BMP配列 から
        andi.l  #$000000F0,d1           ; 上位ニブルを取り出す
        lsr.w   #4,d1                   ; 右に4ビットシフト
        move.w  d1,(a1)                 ; GR配列 に書き込み
        addq.l  #2,a1                   ; GR配列 を次の要素へ(GR配列は 1ドット2バイト)

        move.b  (a0),d1                 ; BMP配列 から
        andi.l  #$0000000F,d1           ; 下位ニブルを取り出す
        move.w  d1,(a1)                 ; GR配列 に書き込み
        addq.l  #2,a1                   ; GR配列 を次の要素へ(GR配列は 1ドット2バイト)

        addq.l  #1,a0                   ; BMP配列 を次の要素へ(BMP配列は 1ドット1ニブル)
 
        dbra    d0,@b                   ; d0.wをループカウンタとして使い、cnt回繰り返す

        rts

;------------------------------------------------------------------------------
; GR(n)-VRAM 書き込み
;------------------------------------------------------------------------------
; - IN:   a2.l    buf       : GR配列の先頭アドレス
;         a3.l    vram      : GRnのVRAM先頭アドレス
;         d3.w    widht     : 画像の横幅
;         d4.w    height    : 画像の縦幅-1
;------------------------------------------------------------------------------
; - MEMO:
;   X方向横に1行のDMA転送を,起点を縦に移動しながらY回行うという考え方.
;------------------------------------------------------------------------------
D01234A0123_GrDraw::

        lsl.w   #1,d3                   ; 画像の横幅を一度2倍する
@@:
        move.b  #DMA_SIZE4,d0           ; 転送サイズ：4バイト
        move.b  #5,d1                   ; 転送設定：MAR,DAR共に転送毎インクリメント
        lsr.w   #2,d3                   ; 画像の横幅*2/4(==画像の横幅/2)
        move.w  d3,d2                   ; 転送回数：1ドット2バイトなので4バイト転送なら横幅の半分
        movea.l a2,a0                   ; 転送元アドレス
        movea.l a3,a1                   ; 転送先アドレス

        bsr     D012A01_dma_start_r     ; DMA転送開始
        bsr     D0A0_dma_wait           ; DMA転送完了待ち (d0.b = $00:エラーなし / $10:エラー発生)

        lsl.w   #2,d3                   ; 画像の横幅*2/4*4(==画像の横幅*2)
        add.l   d3,a2                   ; 転送元アドレス：次の行へ(画像横幅*2byte)を加算
        add.l   #512*2,a3               ; 転送先アドレス：次の行へ(スクリーン横幅512*2byte)を加算

        dbra    d4,@b                   ; d4.wをループカウンタとして使い画像の縦幅回繰り返す

        rts


;------------------------------------------------------------------------------
; BMP配列(RAM) → PCG配列(RAM/PCG) 変換 (16 * 16 * 1個 専用)
;------------------------------------------------------------------------------
; - IN:   a0.l    SRC：BMP配列(RAM)の先頭アドレス
;         a1.l    DST：PCG配列(RAM/PCG)の先頭アドレス→PCG直接は $EB8000 を指定する
;         d0.l    書き込むPCG番号:0-255(DSTをPCG直接にしない場合は0を指定すること)
;
; - OUT:  なし
;------------------------------------------------------------------------------
D01A01_BmpToPcg::

        lsl.l   #7,d0                   ; d0の値を128倍にする(16*16のPCGは1枚128バイトなので)
        adda.l  d0,a1                   ; 書き込むPCG番号に応じたオフセットをDSTアドレスに加算

        clr.w   d0                      ; i = 0; for(i = 0; i < 128; i += 8)
        clr.w   d1                      ; index = 0; (0～60) index += 4

@@:     ; 16回ループ(最上段から1ライン毎順に描いていく)

        move.l  0(a0,d0.w), 0(a1,d1.w)  ; pcg[u4_index +  0] = bmp[i + 0];
        move.l  4(a0,d0.w),64(a1,d1.w)  ; pcg[u4_index + 64] = bmp[i + 4]; (+$40)

        addq.w  #8,d0                   ; i     += 8; BMP：ループ1回につき8バイトをコピーしているので
        addq.w  #4,d1                   ; index += 4; PCG：+4バイトでY方向に1段下がるので

        cmp.w   #128,d0                 ; if(d0 < 128)
        bcs     @b                      ; then bra @b

        rts

;------------------------------------------------------------------------------
; PCG配列(RAM) → PCG配列(RAM/PCG) DMA転送 (_SP_DEFCG と同等の作用)
;------------------------------------------------------------------------------
; - IN:   a0.l    SRC：PCG配列(RAM)の先頭アドレス
;         a1.l    DST：PCG配列(RAM/PCG)の先頭アドレス→PCG直接は $EB8000 を指定する
;         d0.l    書き込むPCG番号:0-255(DSTをPCG直接にしない場合は0を指定すること)
;
; - OUT:  なし
;------------------------------------------------------------------------------
D012A01_PcgToPcg::

        lsl.l   #7,d0                   ; d0の値を128倍にする(16*16のPCGは1枚128バイトなので)
        adda.l  d0,a1                   ; 書き込むPCG番号に応じたオフセットをDSTアドレスに加算

        move.b  #DMA_SIZE4,d0           ; 転送サイズ：4バイト
        move.b  #5,d1                   ; 転送設定：MAR,DAR共に転送毎インクリメント
        move.w  #32,d2                  ; 転送回数：4バイト転送*32回=128バイト(PCGパターン1枚分)
                                        ; a0.l：転送元, a1.l：転送先 はそのままDMACに渡る

        bsr     D012A01_dma_start_r     ; DMA転送開始
        bsr     D0A0_dma_wait           ; DMA転送完了待ち (d0.b = $00:エラーなし / $10:エラー発生)

        rts

;------------------------------------------------------------------------------
; SP_REGST()やBGに渡すパターンコードを生成する
;------------------------------------------------------------------------------
; - IN:   d0.l    vh  : 指定しない ------------   OFF : $0000 0000
;                     : v  垂直(上下)反転 -----  V_ON : $0000 8000
;                     : h  水平(左右)反転 -----  H_ON : $0000 4000
;                     : vh 同時指定 ----------- VH_ON : $0000 C000
;
;         d1.l    pb  : パレットブロックNo. --- 0～15
;         d2.l    pcg : PCGパターンNo. -------- 0～255
;
; - OUT:  d3.l    ptc : パターンコード ($C6 _SP_REGSTの引数はd4.l)
;------------------------------------------------------------------------------
; - MEMO:
;   パターンコードのフォーマット
;   %VH00_CCCC_SSSSSSSS
;   V=上下反転 / H=左右反転 / C=パレット番号 / S=スプライトパターン番号
;------------------------------------------------------------------------------
D0123Ax_MkSpPtc::

        clr.l   d3                      ; out:パターンコード格納先 ptc = 0;

        ; ALL 0                         ; BIT:16-32    常時0

                                        ; BIT:15       V-垂直反転(0:標準/1:反転)
        add.l   d0,d3                   ; BIT:14       H-水平反転(0:標準/1:反転)

        ; ALL 0                         ; BIT:12-13    常時0

        lsl.l   #8,d1                   ; 左に8ビットシフト ptc += (pb << 8);
        add.l   d1,d3                   ; BIT:8-11     パレットブロックNo.(0-15)

        add.l   d2,d3                   ; BIT:0-7      PCGパターンNo.(0-255)

        rts

;------------------------------------------------------------------------------
; スプライトを表示 (_SP_REGST と同等の作用)
;------------------------------------------------------------------------------
; - IN:   d0.l = 表示するスプライトの番号(0 - 127)
;         d1.w = %000000XXXXXXXXXX   X座標
;         d2.w = %000000YYYYYYYYYY   Y座標
;         d3.w = %VH00_CCCC_SSSSSSSS パターンコード
;         d4.w = %00000000000000PP   PP : 00=表示OFF / 01=BG0>BG1>SP / 10=BG0>SP>BG1 / 11=SP>BG0>BG1
;
; - OUT:  なし
;------------------------------------------------------------------------------
D01234A0_PutSp::

        lea.l   $EB0000,a0              ; スプライト・スクロールレジスタ#0(#0～#127全体の先頭)アドレス
        ext.l   d0                      ; d0の値をワードからロングワードに拡張する
        lsl.l   #3,d0                   ; d0の値を8倍にする → スプライト・スクロールレジスタは1つ8バイト
        adda.l  d0,a0                   ; なので対象スプライト番号*8を#0のアドレスに足せば良い

        ; スプライト情報を書き込んでスプライトを表示する
        move.w  d1,(a0)+                ; X座標
        move.w  d2,(a0)+                ; Y座標
        move.w  d3,(a0)+                ; パターンコード
        move.w  d4,(a0)                 ; プライオリティ

        rts
