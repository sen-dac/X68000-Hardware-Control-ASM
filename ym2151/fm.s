;------------------------------------------------------------------------------
; パラメータ設定 [C] KC ($28[CH.1]～$2F[CH.8])
;------------------------------------------------------------------------------
_F_KC           .macro prm,index

        lea     fm_vreg_top,a0          ; a0 = 仮想レジスタ先頭アドレス
        move.w  index,d1                ; index(レジスタ番号)

        move.b  prm,(a0,d1.w)           ; 仮想レジスタに書き込み
        _F_SREG prm,index               ; 現物レジスタに書き込み

                .endm

;------------------------------------------------------------------------------
; パラメータ設定 [C] L-chEN ON/OFF ($20[CH.1]～$27[CH.8])
;------------------------------------------------------------------------------
_F_LCEN         .macro prm,index

        move.b  prm,d0                  ; パラメータ
        rol.b   #6,d0                   ; 7ビット左シフト(はみ出した分は反対側から出てくる)
        andi.b  #%0100_0000,d0          ; パラメータから当該ビット以外をクリア

        lea     fm_vreg_top,a0          ; a0 = 仮想レジスタ先頭アドレス
        move.w  index,d1                ; index(レジスタ番号)

        move.b  (a0,d1.w),d2            ; d2 = fm_mir_top[index];
        andi.b  #%1011_1111,d2          ; 仮想レジスタ値からパラメータの当該ビットをクリア

        or.b    d0,d2                   ; パラメータを仮想レジスタ値に合成
        move.b  d2,(a0,d1.w)            ; 仮想レジスタに書き込み
        _F_SREG d2,index                ; 現物レジスタに書き込み

                .endm

