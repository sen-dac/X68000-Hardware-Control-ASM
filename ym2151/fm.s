; $09 Reserved ----------> 現物レジスタ：Reserved
; $0A Reserved ----------> 現物レジスタ：Reserved
; $0B TEST(LFO-Reset) ---> 現物レジスタ：Reserved
; $0C Reserved ----------> 現物レジスタ：Reserved
; $0D Reserved ----------> 現物レジスタ：Reserved
; $0E Reserved ----------> 現物レジスタ：Reserved
