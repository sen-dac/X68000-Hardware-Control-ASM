        lea     fm_vreg_top,a0          ; a0 = 仮想レジスタ先頭アドレス
        move.w  index,d0                ; index
        move.b  (a0,d0.w),d1            ; d1 = fm_mir_top[index];
        _F_SREG d1,index                ; 現物レジスタに書き込み

                .endm

;------------------------------------------------------------------------------
; FM音源 現物レジスタ直接書き込み 
;------------------------------------------------------------------------------
; ・基本的にパラメータ設定マクロ以外からは使用しないこと(仮想レジスタ整合維持)
; ・アセンブラ命令に合わせて引数を src,dst の順に変更
; ・BUSY待ち処理を統合
;------------------------------------------------------------------------------
; BUSYフラグについての実験結果：
;
; - XM6 TypeG 10/24MHz (version 3.37) 及び X68000 Z PE(v 1.7.3)
;   BUSYフラグそのものは立つが、待たなくても鳴る。
;   BUSYフラグの細かい挙動は、XM6 TypeGとZで多少異なるが、どうでも良い。
;   実機の挙動に合わせてBUSY待ち処理を入れるべき。
;
; - 実機 10/16/24MHz (Compact XVI)
;   (a) BUSY待ちをしない
;   (b) FM_SEL($E90001)の前で待たずに、FM_DAT($E90003)の前で待つ
;   (a),(b)は、どちらも鳴らなくなる "ときがある" (鳴ってしまう場合の方が多い)。
;   "鳴らない" の発生率は、10/16/24MHzどれも同じと思われる。
;   必ず、FM_SEL($E90001)の前でBUSY待ちをする必要がある。
;   逆に言えば、FM_SEL($E90001)の前だけで待てば鳴る(数十回確認した限りでは)。
;------------------------------------------------------------------------------
_F_SREG         .macro prm,index

@busy_loop:                             ; BUSYフラグ確認
        move.b  FM_DAT,d7               ; Readすると無条件でステータスレジスタとなる
        andi.b  #$80,d7                 ; bit:7(BUSYフラグ)を抽出
        bne     @busy_loop              ; 1(BUSY)なら待つ(レジスタ書込み時に'0'である必要がある)

        move.b  index,FM_SEL            ; レジスタ選択
        move.b  prm,FM_DAT              ; データ書き込み

                .endm

;------------------------------------------------------------------------------
; メイン処理
;------------------------------------------------------------------------------
main:

; アプリケーション 初期化処理
main_init:

        clr.l   -(sp)                   ; 引数：0
        DOS     _SUPER                  ; $ff20 スーパーバイザモード ON
        addq.l  #4,sp                   ; sp戻し
        move.l  d0,ssp_work             ; ssp保存

        ; 仮想レジスタのクリア(一応) ------------------------------------------
        lea     fm_vreg_top,a0          ; a0 = 仮想レジスタ先頭アドレス
        move.w  #256-1,d7               ; ループ回数-1を設定(dbraはdnをwサイズで参照する)
@@:
        move.b  #$00,(a0,d7.w)          ; fm_vreg_top[dn.w] = 0;
        dbra    d7,@b                   ; dn.w --; → if(dn.w == -1){ ループ終了;}

        ; ※ 以下、全てCH.1を使用

        ; FM音源 初期化 -------------------------------------------------------
        _F_KOFF #0000                   ; [M] KON OFF
        _F_LCEN c_lch_en,#$0020         ; [C] L-chEN  ON / OFF : OFFだと左側の音が鳴らない
        _F_RCEN c_rch_en,#$0020         ; [C] R-chEN  ON / OFF : OFFだと右側の音が鳴らない

        ; VOPM 画面 枠外 ------------------------------------------------------
        _F_CON  c_con,#$20              ; [C] CON     (CH.1) パラメータセット

        ; PROG 枠 -------------------------------------------------------------
        _F_M1SW cm_opmsk_m1,#$0000      ; [C/M] OpMsk M1オペレータ ON / OFF
        _F_C1SW cm_opmsk_c1,#$0000      ; [C/M] OpMsk C1オペレータ ON / OFF
        _F_M2SW cm_opmsk_m2,#$0000      ; [C/M] OpMsk M2オペレータ ON / OFF
        _F_C2SW cm_opmsk_c2,#$0000      ; [C/M] OpMsk C2オペレータ ON / OFF

        _F_AMSE s_ams_en_m1,#$00A0      ; [S] AMS-En M1 ON / OFF
        _F_AMSE s_ams_en_c1,#$00B0      ; [S] AMS-En C1 ON / OFF
        _F_AMSE s_ams_en_m2,#$00A8      ; [S] AMS-En M2 ON / OFF
        _F_AMSE s_ams_en_c2,#$00B8      ; [S] AMS-En C2 ON / OFF
        _F_NE   m_noise_en,#$000F       ; [M] NE ノイズ ON / OFF
        _F_FL   c_fl,#$0020             ; [C] FL
        _F_AMS  c_ams,#$0038            ; [C] AMS
        _F_PMS  c_pms,#$0038            ; [C] PMS
        _F_NFRQ m_nfrq                  ; [M] NFRQ (ノイズ周波数)

        ; LFO 枠 --------------------------------------------------------------
        _F_LFOW m_lfo_w                 ; [M] LFO-W (ノイズ波形選択)
        _F_LFRQ m_lfrq                  ; [M] LFRQ
        _F_AMD  m_amd                   ; [M] AMD
        _F_PMD  m_pmd                   ; [M] PMD

        ; OP 枠 ---------------------------------------------------------------
        _F_TL   s_tl_m1,#$0060          ; [S] TL M1
        _F_TL   s_tl_c1,#$0070          ; [S] TL C1
        _F_TL   s_tl_m2,#$0068          ; [S] TL M2
        _F_TL   s_tl_c2,#$0078          ; [S] TL C2

        _F_AR   s_ar_m1,#$0080          ; [S] AR M1
        _F_AR   s_ar_c1,#$0090          ; [S] AR C1
        _F_AR   s_ar_m2,#$0088          ; [S] AR M2
        _F_AR   s_ar_c2,#$0098          ; [S] AR C2

        _F_D1R  s_d1r_m1,#$00A0         ; [S] D1R M1
        _F_D1R  s_d1r_c1,#$00B0         ; [S] D1R C1
        _F_D1R  s_d1r_m2,#$00A8         ; [S] D1R M2
        _F_D1R  s_d1r_c2,#$00B8         ; [S] D1R C2

        _F_D1L  s_d1l_m1,#$00E0         ; [S] D1L M1
        _F_D1L  s_d1l_c1,#$00F0         ; [S] D1L C1
        _F_D1L  s_d1l_m2,#$00E8         ; [S] D1L M2
        _F_D1L  s_d1l_c2,#$00F8         ; [S] D1L C2

        _F_D2R  s_d2r_m1,#$00C0         ; [S] D1L M1
        _F_D2R  s_d2r_c1,#$00D0         ; [S] D1L C1
        _F_D2R  s_d2r_m2,#$00C8         ; [S] D1L M2
        _F_D2R  s_d2r_c2,#$00D8         ; [S] D1L C2

        _F_RR   s_rr_m1,#$00E0          ; [S] RR M1
        _F_RR   s_rr_c1,#$00F0          ; [S] RR C1
        _F_RR   s_rr_m2,#$00E8          ; [S] RR M2
        _F_RR   s_rr_c2,#$00F8          ; [S] RR C2

        _F_KS   s_ks_m1,#$0080          ; [S] KS M1
        _F_KS   s_ks_c1,#$0090          ; [S] KS C1
        _F_KS   s_ks_m2,#$0088          ; [S] KS M2
        _F_KS   s_ks_c2,#$0098          ; [S] KS C2

        _F_MUL  s_mul_m1,#$0040         ; [S] MUL M1
        _F_MUL  s_mul_c1,#$0050         ; [S] MUL C1
        _F_MUL  s_mul_m2,#$0048         ; [S] MUL M2
        _F_MUL  s_mul_c2,#$0058         ; [S] MUL C2

        _F_DT1  s_dt1_m1,#$0040         ; [S] DT1 M1
        _F_DT1  s_dt1_c1,#$0050         ; [S] DT1 C1
        _F_DT1  s_dt1_m2,#$0048         ; [S] DT1 M2
        _F_DT1  s_dt1_c2,#$0058         ; [S] DT1 C2

        _F_DT2  s_dt2_m1,#$00C0         ; [S] DT2 M1
        _F_DT2  s_dt2_c1,#$00D0         ; [S] DT2 C1
        _F_DT2  s_dt2_m2,#$00C8         ; [S] DT2 M2
        _F_DT2  s_dt2_c2,#$00D8         ; [S] DT2 C2

; アプリケーション 実行処理
main_loop:

        jbsr    Input_1P_CreateData     ; 入力情報作成

        ; Zキーが押されたら音('ド4'C4[261.626Hz]近似値)を鳴らす
        move.w  #BTN_B__,d0             ; d0.w ボタン：Xキー
        move.w  #BS_DOW,d1              ; d1.w 状態  ：押した瞬間
        jbsr    Input_1P_GetState       ; コントローラ n の入力情報を取得する
        tst.w   d0                      ; 0(非成立)か？
        beq     @f                      ; 0(非成立)なら抜ける
        _F_KOFF #0000                   ; [M] KON OFF
        _F_KC   #$3C,#$0028             ; [C] KC  OCT=3, NOTE=$C ('ド4'C4[261.626Hz]近似値)
        _F_KON  #0000                   ; [M] KON ON
@@:
        ; Zキーが離されたら音を消す
        move.w  #BTN_B__,d0             ; d0.w ボタン：Xキー
        move.w  #BS_UP_,d1              ; d1.w 状態  ：離した瞬間
        jbsr    Input_1P_GetState       ; コントローラ n の入力情報を取得する
        tst.w   d0                      ; 0(非成立)か？
        beq     @f                      ; 0(非成立)なら抜ける
        _F_KOFF #0000                   ; [M] KON OFF
@@:
        ; Xキーが押されたら音('レ4'D4[293.665Hz]近似値)を鳴らす
        move.w  #BTN_A__,d0             ; d0.w ボタン：Xキー
        move.w  #BS_DOW,d1              ; d1.w 状態  ：押した瞬間
        jbsr    Input_1P_GetState       ; コントローラ n の入力情報を取得する
        tst.w   d0                      ; 0(非成立)か？
        beq     @f                      ; 0(非成立)なら抜ける
        _F_KOFF #0000                   ; [M] KON OFF
        _F_KC   #$3E,#$0028             ; [C] KC  OCT=3, NOTE=$E ('レ4'D4[293.665Hz]近似値)
        _F_KON  #0000                   ; [M] KON ON
@@:
        ; Xキーが離されたら音を消す
        move.w  #BTN_A__,d0             ; d0.w ボタン：Xキー
        move.w  #BS_UP_,d1              ; d1.w 状態  ：離した瞬間
        jbsr    Input_1P_GetState       ; コントローラ n の入力情報を取得する
        tst.w   d0                      ; 0(非成立)か？
        beq     @f                      ; 0(非成立)なら抜ける
        _F_KOFF #0000                   ; [M] KON OFF
@@:
        ; スペースキーが押されたらアプリ終了
        move.w  #BTN_STA,d0             ; d0.w ボタン：スペースキー
        move.w  #BS_DOW,d1              ; d1.w 状態  ：押した瞬間
        jbsr    Input_1P_GetState       ; コントローラ n の入力情報を取得する
        tst.w   d0                      ; 0(非成立)か？
        beq     @f                      ; 0(非成立)なら抜ける
        jbra    main_release            ; アプリケーション終了処理へ
@@:
        jbra    main_loop               ; 次フレームも継続：メインループ先頭へ

; アプリケーション 終了処理
main_release:

        _F_KOFF #0000                   ; [M] KON OFF

        move.l  ssp_work,-(sp)          ; 引数：起動時に保存しておいたssp
        DOS     _SUPER                  ; $ff20 スーパーバイザモード OFF
        addq.l  #4,sp                   ; sp戻し
        DOS     _EXIT                   ; プログラム終了

                .end main
