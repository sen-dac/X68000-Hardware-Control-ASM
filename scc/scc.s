;------------------------------------------------------------------------------
; リングバッファからデータを読み込む
;------------------------------------------------------------------------------
; 使用例：
; RB_Read rx_buff,rxbR_index      ; d1 = リングバッファ内のデータ
;------------------------------------------------------------------------------
RB_Read         .macro buff,index

        lea     buff,a0                 ; a0 = リングバッファ先頭アドレス
        clr.l   d0                      ; .wか.lしか受け付けないのでサイズ拡張のためd0全体をクリア
.if RB256
        move.b  index,d0                ; 全体をクリア済みのd0にインデックスを格納
        move.b  (a0,d0.l),d1            ; リングバッファを読み込み
        add.b   #1,index                ; 必ず読み込みに"読み込み用インデックス"を+1する
.else
        move.w  index,d0                ; 全体をクリア済みのd0にインデックスを格納
        move.b  (a0,d0.l),d1            ; リングバッファを読み込み
        add.w   #1,index                ; 必ず読み込みに"読み込み用インデックス"を+1する
.endif
                .endm

;------------------------------------------------------------------------------
; リングバッファにデータを書き込む
;------------------------------------------------------------------------------
; 使用例：
; RB_Write SCC_DAT,rxbW_index,rx_buff
;------------------------------------------------------------------------------
RB_Write        .macro src,index,buff

        lea     buff,a0                 ; a0 = リングバッファ先頭アドレス
        clr.l   d0                      ; .wか.lしか受け付けないのでサイズ拡張のためd0全体をクリア
.if RB256
        move.b  index,d0                ; 全体をクリア済みのd0にインデックスを格納
        move.b  src,(a0,d0.l)           ; リングバッファに書き込み
        add.b   #1,index                ; 必ず書き込み後に"書き込み用インデックス"を+1する。
.else
        move.w  index,d0                ; 全体をクリア済みのd0にインデックスを格納
        move.b  src,(a0,d0.l)           ; リングバッファに書き込み
        add.w   #1,index                ; 必ず書き込み後に"書き込み用インデックス"を+1する。
.endif
                .endm

;------------------------------------------------------------------------------
; リングバッファにデータが有るかを返す
;------------------------------------------------------------------------------
; 使用例：
; RB_IsEm rxbR_index,rxbW_index
; beq     @f                      ; 0(=)が戻った場合：データが無いのでジャンプ
;------------------------------------------------------------------------------
RB_IsEm         .macro R_index,W_index
.if RB256
        move.b  R_index,d0              ; cmpのために読み込み用インデックスをレジスタ格納
        move.b  W_index,d1              ; cmpのために書き込み用インデックスをレジスタ格納
        cmp.b   d0,d1                   ; 読み込みインデックスと書き込みインデックスが一致しているか？
.else
        move.w  R_index,d0              ; cmpのために読み込み用インデックスをレジスタ格納
        move.w  W_index,d1              ; cmpのために書き込み用インデックスをレジスタ格納
        cmp.w   d0,d1                   ; 読み込みインデックスと書き込みインデックスが一致しているか？
.endif
                .endm

;------------------------------------------------------------------------------
; [MPU] マスカブル割り込み禁止
; この処理(_EI)は、コール直前のCCRを維持できる
;------------------------------------------------------------------------------
; 変更点：(2025-06-25ver) → (2026-04-20ver)
; 1. 以前は_DIにてSRをメモリ(sr_work)に保存していたが、意図せずネストになった場合を考慮してスタックに変更。
;------------------------------------------------------------------------------
_DI             .macro

        move.w  sr, -(sp)               ; CCR変化なし (青本P.271)：SRの値をスタックに保存
        ori.w   #%00000111_00000000,sr  ; CCR変化なし (青本P.333)：SRの割り込みマスクビットにレベル7(111) NMI以外全割禁)を設定

                .endm

;------------------------------------------------------------------------------
; XM6 TypeG + scd.x による _DI,_EI の単体検査結果 (2026-04-20 実施)
;------------------------------------------------------------------------------
; [OK] SPが_DIの後_EI実行した後、正しく_DI実行前に戻る事を確認済み
; [OK] _DIにて指定した割り込みレベル(111)になる事を確認済み
; [OK] _DI,_EIともにCCRを変化させない事を確認済み (テストコード: move #$15,ccr ;(XNZVC:10101)
; [OK] _DI前の割り込みレベルに_EI終了時に戻る事を確認済み (テストコード: move.w  #$A515,sr(intLV:101, XNZVC:10101)
; [OK] _DI,_EIともにレジスタ値は実行前と変わらない事を確認済み (コール前にレジスタ値を特徴的な値に変更して確認)
;------------------------------------------------------------------------------
;
;------------------------------------------------------------------------------
; [MPU] マスカブル割り込み許可
; この処理(_EI)は、コール直前のCCRを維持できる
;------------------------------------------------------------------------------
; 変更点：(2025-06-25ver) → (2026-04-20ver)
; 1. 以前は_DIにてSRをメモリ(sr_work)に保存していたが、意図せずネストになった場合を考慮してスタックに変更。
; 2. バグ修正～現在のSRの値が変更された後に保存してしまっていたので、保存のタイミングを修正。
; ※ 必ず事前に_DIをコールして一対で使用すること。
;------------------------------------------------------------------------------
mac_ei_sreg     reg     d0-d1           ; スタックに退避するMPUレジスタのリスト
_EI             .macro

        movem.l mac_ei_sreg,-(sp)       ; CCR変化なし (青本P.275)：MPUレジスタをスタック退避

        move.w  sr,d1                   ; CCR変化なし (青本P.271)：現在のSRを保存
        andi.w  #%11111000_11111111,d1  ; CCR変化あり (青本P.322)：_EIにて保存したSRの値からマスクビットのみ0クリア(次のor合成のため)
        move.w  8(sp),d0                ; CCR変化あり (青本P.267)：_DIにて保存したSRの値をスタックから取り出す
        andi.w  #%00000111_00000000,d0  ; CCR変化あり (青本P.322)：_DIにて保存したSRの値からマスクビットのみ抽出
        or.w    d0,d1                   ; CCR変化あり (青本P.330)：_DIにて保存したSRのマスクビットを_EIにて保存したSRに合成する
        move.w  d1,sr                   ; CCR更新     (青本P.270)：_EIにて保存したSRの値と_DIにて保存したマスクビットの値を合成したものをMPUのSRを復旧

        movem.l (sp)+,mac_ei_sreg       ; CCR変化なし (青本P.277)：スタック待避したMPUレジスタを復旧

        addq.l  #2, sp                  ; CCR変化なし (青本P.294)：_DI時のSR保持分のスタックを掃除 (dstがアドレスレジスタ直接形式の場合CCRはaddqの影響を受けない)

                .endm

